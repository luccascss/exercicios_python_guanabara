t1 = input('Digite algo ')
print('O tipo primitivo dele é ', type(t1))
print('Está em branco?', t1.isspace())
print('É um número? ', t1.isnumeric())
print('É alfabético? ', t1.isalpha())
print('É alfanumérico? ', t1.isalnum())
print('Está em CAPSLOCK? ', t1.isupper())
print('Está em letra minúscula? ', t1.islower())
print('Está capitalizada? ', t1.istitle())




